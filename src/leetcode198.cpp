/*
============================================================================
LeetCode 198. 打家劫舍（House Robber）
https://leetcode.cn/problems/house-robber/
============================================================================
题目描述：

  你是一个专业的小偷，计划偷窃沿街的房屋。每间房内都藏有一定的现金，
  影响你偷窃的唯一制约因素就是 相邻的房屋装有相互连通的防盗系统，
  如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。

  给定一个代表每个房屋存放金额的非负整数数组 nums，
  计算你 不触动警报装置的情况下，一夜之内能够偷窃到的最高金额。

----------------------------------------------------------------------------
示例 1：
  输入：nums = [1,2,3,1]
  输出：4
  解释：偷 1 号房（金额 1），然后偷 3 号房（金额 3）。最高金额 = 1 + 3 = 4

示例 2：
  输入：nums = [2,7,9,3,1]
  输出：12
  解释：偷 1 号房（金额 2）、3 号房（金额 9）、5 号房（金额 1）。
        最高金额 = 2 + 9 + 1 = 12

----------------------------------------------------------------------------
提示（数据范围）：
  1 <= nums.length <= 100
  0 <= nums[i] <= 400

----------------------------------------------------------------------------
思路提示（真正的 DP 推理由你完成）：

  仿照爬楼梯的思考方式，问自己：对第 i 间房，你只有两个选择——
  偷，或者不偷。

    设 f(i) = 前 i 间房能偷到的最高金额（考虑完第 i 间后的最优结果）

    - 不偷第 i 间：最高金额 = f(i-1)
    - 偷第 i 间：第 i-1 间就不能偷了，最高金额 = f(i-2) + nums[i]

    两者取大：
      f(i) = max(f(i-1), f(i-2) + nums[i])

  边界自己推：f(0) = ? f(1) = ?（只有一间房 / 两间房时怎么办）

  注意和爬楼梯的区别：
    爬楼梯的转移是无条件相加 f(n) = f(n-1) + f(n-2)，
    这题多了一个 max 决策 —— 这是 DP 里"选或不选"的经典模型。

  复杂度：O(n) 时间；空间 O(n)（数组版）可优化到 O(1)（滚动变量）。
============================================================================
*/

#include <algorithm>
#include <iostream>
#include <vector>

using namespace std;

class Solution {
public:
    int rob(std::vector<int> &nums) {
        // TODO(你来做)：
        //   1. 处理边界：nums 只有 1 个或 2 个元素时
        //   2. 按上面的转移方程递推（数组版或滚动变量版都行）
        //   3. 返回答案
        if (nums.size() == 1) {
            return nums[0];
        }
        vector<int> vec(nums.size());
        vec[0] = nums[0];
        vec[1] = std::max(nums[0], nums[1]);
        for (size_t idx = 2; idx < nums.size(); ++idx) {
            vec[idx] = std::max(vec[idx - 1], nums[idx] + vec[idx - 2]);
        }

        return vec[nums.size() - 1];
    }
};

void test(std::vector<int> nums, int expected) {
    int got = Solution().rob(nums);
    std::cout << (got == expected ? "PASS" : "FAIL") << " -> expected = " << expected
              << ", got = " << got << '\n';
}

int main() {
    test({1, 2, 3, 1}, 4);      // 示例 1
    test({2, 7, 9, 3, 1}, 12);  // 示例 2
    test({5}, 5);               // 只有一间
    test({5, 10}, 10);          // 两间取大
    test({1, 1, 1, 1}, 2);      // 隔间偷
    test({2, 1, 1, 2}, 4);      // 首尾各偷一间（贪心会错！）
    test({0, 0, 0}, 0);         // 全是 0
    return 0;
}
